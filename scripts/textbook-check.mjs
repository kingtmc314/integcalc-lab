import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';

const base=process.env.TEST_URL||'http://127.0.0.1:4173';
const out=process.env.TEST_OUTPUT||'/home/ubuntu/integcalc-textbook-check';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--enable-unsafe-swiftshader']});
const errors=[],checks=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>errors.push(e.message));
const pass=text=>{checks.push(text);console.log('PASS',text);};
const theorem=number=>page.locator(`[id="theorem-${number}"]`);

await page.goto(base);
await page.locator('.hero-math-note .reference-link').click();
await theorem('1.2').waitFor();
assert.ok(page.url().endsWith('/#/formulas?ref=1.2'));
assert.match(await theorem('1.2').innerText(),/Theorem\s+1\.2/);
assert.equal(await theorem('1.2').getAttribute('class'),'formula-row theorem-row referenced-theorem');
await page.waitForTimeout(200);
assert.ok((await theorem('1.2').boundingBox()).y>=0);
pass('Homepage theorem link opens and highlights FTC 1.2');
assert.equal(await page.locator('.theorem-row').count(),3);
assert.equal(await page.locator('.theorem-badge').count(),3);
assert.equal(await page.locator('.theorem-conditions').count(),3);
assert.equal(await page.locator('.theorem-context').count(),3);
pass('Only the three intended theorems have theorem numbers, conditions and variable context');
await page.getByRole('button',{name:'繁中',exact:true}).click();
assert.match(await theorem('1.2').innerText(),/定理\s+1\.2/);
assert.match(await theorem('1.2').innerText(),/原函數/);
assert.match(await theorem('1.2').innerText(),/下端點/);
assert.equal(await page.locator('.katex-error').count(),0);
await theorem('1.2').screenshot({path:out+'/theorem-1-2-zh.png'});
pass('Theorem labels, conditions and LaTeX variable explanations switch to Traditional Chinese');
await page.getByRole('button',{name:'積分技巧',exact:true}).click();
assert.equal(await page.locator('.theorem-badge').count(),0);
assert.ok(await page.locator('.reference-badge').count()>0);
assert.match(await page.locator('.reference-badge').first().innerText(),/公式\s+2\.1\.1/);
pass('Techniques and ordinary entries use formula numbers, not fake theorem labels');

await page.goto(base+'/#/presets');
assert.equal(await page.locator('.example-card').count(),22);
assert.equal(await page.locator('.example-methods').count(),22);
assert.match(await page.locator('[data-example-id="v1"] .example-methods').innerText(),/圓盤法/);
assert.match(await page.locator('[data-example-id="v4"] .example-methods').innerText(),/墊圈法/);
assert.match(await page.locator('[data-example-id="v5"] .example-methods').innerText(),/圓柱殼法/);
assert.match(await page.locator('[data-example-id="a9"] .example-methods').innerText(),/分部積分/);
assert.match(await page.locator('[data-example-id="v7"] .example-methods').innerText(),/半角公式/);
await page.screenshot({path:out+'/desktop-examples-zh.png'});
pass('All 22 example cards show the appropriate solution and documented technique tags');
const search=page.getByRole('textbox',{name:'搜尋例題',exact:true});
await search.fill('圓柱殼法');
assert.equal(await page.locator('.example-card').count(),2);
await page.getByRole('button',{name:'EN',exact:true}).click();
assert.equal(await page.locator('.example-card').count(),2);
assert.match(await page.locator('.example-methods').first().innerText(),/Cylindrical shell method/);
pass('Chinese method search and selected results survive the switch to English');
await page.getByRole('textbox',{name:'Search examples',exact:true}).fill('Integration by parts');
assert.equal(await page.locator('.example-card').count(),2);
await page.getByRole('textbox',{name:'Search examples',exact:true}).fill('v7');
assert.equal(await page.locator('.example-card').count(),1);
await page.locator('.example-card').getByRole('button').click();
await page.waitForURL('**/#/volume');
await page.getByRole('button',{name:'Calculate & derive',exact:true}).click();
await page.locator('[data-testid=result]').waitFor();
assert.match((await page.locator('[data-testid=result] .katex-mathml').innerText()).normalize('NFKC'),/π/);
pass('English method and example-ID searches work; filtered example still loads and computes');
await page.goto(base+'/#/learn');
await page.locator('[data-testid=derivation]').waitFor();
await page.locator('.stage-track button').last().click();
await page.locator('.derivation-reference .reference-link').click();
await theorem('1.2').waitFor();
assert.ok(page.url().endsWith('/#/formulas?ref=1.2'));
pass('Final derivation step links to the same FTC 1.2 reference');

const phone=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
phone.on('pageerror',e=>errors.push(e.message));
await phone.goto(base);await phone.getByRole('button',{name:'繁中',exact:true}).click();
await phone.locator('.hero-math-note .reference-link').click();
await phone.locator('[id="theorem-1.2"]').waitFor();await phone.waitForTimeout(200);
assert.ok((await phone.locator('[id="theorem-1.2"]').boundingBox()).y>=114);
await phone.screenshot({path:out+'/mobile-theorem-zh.png'});
pass('Mobile theorem deep-link scrolls below the sticky navigation');
await phone.goto(base+'/#/presets');await phone.getByRole('textbox',{name:'搜尋例題',exact:true}).fill('圓盤法');
await phone.screenshot({path:out+'/mobile-method-tags-zh.png'});
assert.ok(await phone.locator('.example-card').count()>0);
for(const width of [320,390,768]){
 await phone.setViewportSize({width,height:844});
 for(const route of ['/','/presets','/formulas?ref=1.2']){
  await phone.goto(base+'/#'+route);await phone.waitForTimeout(150);
  assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.equal(await phone.locator('.katex-error').count(),0);
 }
 pass(`${width}px layout: overview, method tags and referenced theorem have no overflow or LaTeX errors`);
}
assert.deepEqual(errors,[]);
await writeFile(out+'/textbook-results.json',JSON.stringify({passed:checks.length,checks,errors},null,2));
await browser.close();
console.log('All textbook browser checks passed:',checks.length);
